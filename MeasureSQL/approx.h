class Plane;
class Vector3d;
class Segment3d;

//*******************************************************************//
//
//      Аппроксимация прямой набора из n трёхмерных точек.
//      Вычисляются направление вдоль прямой ( единичный вектор dir )
//      и точка point через которую проходит прямая ( она является
//      средним арифметическим значением от исходных точек ).
//
//*******************************************************************//

bool getLine ( const int n, const Vector3d * v, Vector3d & dir, Vector3d & point );


//*******************************************************************//
//
//      Аппроксимация плоскостью набора из n трёхмерных точек.
//      Вычисляются нормаль к плоскости norm ( единичный вектор )
//      и точка point через которую проходит плоскость ( она является
//      средним арифметическим значением от исходных точек ).
//
//*******************************************************************//

bool getPlane ( const int n, const Vector3d * v, Vector3d & norm, Vector3d & point );


//************************ 19.09.2005 *******************************//
//
//      Аппроксимация плоскостью набора из n трёхмерных отрезков.
//      Вычисляются нормаль к плоскости norm ( единичный вектор )
//      и точка point через которую проходит плоскость ( она является
//      центром масс исходных отрезков ).
//
//*******************************************************************//

bool getPlane ( const int n, const Segment3d * segm, Vector3d & norm, Vector3d & point );


//************************ 23.06.2005 *******************************//
//
//      Аппроксимация точек сферой
//      c - центр, r - радиус
//
//*******************************************************************//

bool getSphere ( int n, const Vector3d * p, Vector3d & c, double & r );


//************************ 29.01.2005 *******************************//
